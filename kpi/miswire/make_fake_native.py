"""Write fake_native_describe.h: the lk_describe() JSON of three fake native components (CONTRACT §6.3).

    python kpi/miswire/make_fake_native.py

`ok` exposes a JointState `input` and `output` with the right schema hash; `skew` the same ports with a schema hash
that is not JointState's (criterion 12: "a schema-hash mismatch against a native .so's lk_describe()"); `abi2` claims
ABI 2. CMake compiles kpi/miswire/fake_native.c once per variant (no like_keras needed), so the checks that read
a .so's description work before the C++ runtime exists. The JSON's port records have the shape of describe()'s
(CONTRACT §4.4); the ruler's reading of lk_describe() is in docs/friction/contract-002.md.
"""

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "golden"))

import lkf  # noqa: E402

JOINT_STATE = f"{lkf.schema_hash('sensor/JointState'):016x}"


def describe(hash_value: str, abi: int) -> str:
    port = {"type": "sensor/JointState", "hash": hash_value, "queue": None, "stale": None, "lagged": False}
    return json.dumps({"like_keras": "0.1.0", "abi": abi, "system": "fake",
                       "ports": {"input": {"dir": "in", **port}, "output": {"dir": "out", **port}},
                       "params": {}}, separators=(",", ":"))


def main() -> None:
    variants = {"OK": describe(JOINT_STATE, 1), "SKEW": describe("0123456789abcdef", 1), "ABI2": describe(JOINT_STATE, 2)}
    lines = ["// GENERATED by kpi/miswire/make_fake_native.py; do not edit.", "#pragma once"]
    for name, text in variants.items():
        lines.append(f"#define FAKE_DESCRIBE_{name} {json.dumps(text)}")
    (HERE / "fake_native_describe.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
